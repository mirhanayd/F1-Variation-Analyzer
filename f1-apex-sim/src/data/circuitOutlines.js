// Catmull-Rom -> cubic bezier path for a smooth closed loop.
export const pointsToSmoothPath = (points, { tension = 6 } = {}) => {
  if (!points?.length) return '';

  const count = points.length;
  let path = `M ${points[0][0].toFixed(1)} ${points[0][1].toFixed(1)} `;

  for (let i = 0; i < count; i += 1) {
    const p0 = points[(i - 1 + count) % count];
    const p1 = points[i];
    const p2 = points[(i + 1) % count];
    const p3 = points[(i + 2) % count];

    const c1x = p1[0] + (p2[0] - p0[0]) / tension;
    const c1y = p1[1] + (p2[1] - p0[1]) / tension;
    const c2x = p2[0] - (p3[0] - p1[0]) / tension;
    const c2y = p2[1] - (p3[1] - p1[1]) / tension;

    path += `C ${c1x.toFixed(1)} ${c1y.toFixed(1)}, ${c2x.toFixed(1)} ${c2y.toFixed(1)}, ${p2[0].toFixed(1)} ${p2[1].toFixed(1)} `;
  }

  return `${path}Z`;
};

export const hasCuratedOutline = (circuitId) => Boolean(CIRCUIT_OUTLINES[normalizeCircuitId(circuitId)]);

export const getOutline = (circuitId) => CIRCUIT_OUTLINES[normalizeCircuitId(circuitId)] ?? null;

export const getOutlinePathD = (circuitId) => {
  const outline = getOutline(circuitId);
  return outline ? pointsToSmoothPath(outline.points) : null;
};

// Densely resampled closed loop (Catmull-Rom interpolation) so the outline
// can drive the 2D track canvas and the 3D full-track simulation view.
export const sampleOutlinePoints = (circuitId, { samplesPerSegment = 24 } = {}) => {
  const outline = getOutline(circuitId);
  if (!outline) return null;

  const raw = outline.points;
  const count = raw.length;
  const sampled = [];

  for (let i = 0; i < count; i += 1) {
    const p0 = raw[(i - 1 + count) % count];
    const p1 = raw[i];
    const p2 = raw[(i + 1) % count];
    const p3 = raw[(i + 2) % count];

    for (let step = 0; step < samplesPerSegment; step += 1) {
      const t = step / samplesPerSegment;
      const t2 = t * t;
      const t3 = t2 * t;

      // Catmull-Rom spline interpolation.
      const x = 0.5 * (
        (2 * p1[0])
        + (-p0[0] + p2[0]) * t
        + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2
        + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3
      );
      const y = 0.5 * (
        (2 * p1[1])
        + (-p0[1] + p2[1]) * t
        + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2
        + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3
      );

      sampled.push({ x, y });
    }
  }

  // Close the loop explicitly.
  sampled.push({ ...sampled[0] });
  return sampled;
};

// Geometry object compatible with TrackCanvas / TrackRenderer.
export const getOutlineGeometry = (circuitId) => {
  const points = sampleOutlinePoints(circuitId);
  if (!points) return null;

  return buildGeometry(points, {
    source: 'curated-outline',
    coordinateSpace: 'svg',
    closed: true,
  });
};

// Builds a metric path (x/y in metres, heading + cumulative distance) for
// the 3D full-track simulation view. The outline is scaled so its arc
// length matches the circuit's real lap length when known.
export const buildFullTrackPath = (circuitId, { lengthMeters = 5000 } = {}) => {
  const sampled = sampleOutlinePoints(circuitId, { samplesPerSegment: 32 });
  if (!sampled) return null;

  // Raw arc length in outline units.
  let rawLength = 0;
  for (let i = 1; i < sampled.length; i += 1) {
    rawLength += Math.hypot(sampled[i].x - sampled[i - 1].x, sampled[i].y - sampled[i - 1].y);
  }
  if (rawLength <= 0) return null;

  const scale = lengthMeters / rawLength;

  // Convert to metres, flip y so the path lives in a y-up world space.
  const points = [];
  let s = 0;
  for (let i = 0; i < sampled.length; i += 1) {
    const x = sampled[i].x * scale;
    const y = -sampled[i].y * scale;
    if (i > 0) {
      s += Math.hypot(x - points[i - 1].x, y - points[i - 1].y);
    }
    points.push({ x, y, s, zone: 'arc' });
  }

  // Headings from neighbouring points.
  for (let i = 0; i < points.length; i += 1) {
    const prev = points[(i - 1 + points.length) % points.length];
    const next = points[(i + 1) % points.length];
    points[i].heading = Math.atan2(next.y - prev.y, next.x - prev.x);
  }

  return {
    points,
    totalLength: s,
  };
};
