export const normalizeCircuitId = (circuitId = '') => {
  const normalized = circuitId.toLowerCase().replaceAll('-', '_').replaceAll(' ', '_');
  return CIRCUIT_ALIASES[normalized] ?? normalized;
};

export const getCircuitById = (circuitId) => CURATED_CIRCUITS[normalizeCircuitId(circuitId)];

export const getCircuitBySlug = (slug) => Object.values(CURATED_CIRCUITS)
  .find((circuit) => circuit.slug === slug || circuit.id === slug);

export const getCircuitByOpenF1Name = (name = '') => {
  const safeName = name.toLowerCase();

  return Object.values(CURATED_CIRCUITS).find((circuit) => (
    circuit.openF1?.circuitShortNames?.some((entry) => entry.toLowerCase() === safeName)
  ));
};

export const getCuratedCircuitList = () => Object.values(CURATED_CIRCUITS);
